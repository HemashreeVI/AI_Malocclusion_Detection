"""Analysis summary, plain-text report and PDF export.

The PDF is built from the structured summary (not by re-parsing the text
report) and uses a Unicode TTF font when one is available, so nothing turns
into '?'.
"""
import datetime
import glob
import os
import tempfile

from fpdf import FPDF
from fpdf.fonts import FontFace

from .config import (CATEGORY_LABELS, COST_REGION_NOTE, SEVERITY_ORDER, gating_rule,
                     reliability_note)
from .findings import cost_items, ortho_discussion_points, risk_score, risk_status

DISCLAIMER = ('This report was generated by an AI research tool for informational purposes only. '
              'It is not a diagnosis. Findings, tooth numbers and cost ranges must be confirmed by '
              'a licensed dental professional.')


def summarize(detections, conf_threshold, patient=None, cam_note=''):
    patient = patient or {}
    score = risk_score(detections)
    status, status_text = risk_status(score)
    rows, cmin, cmax = cost_items(detections)
    points, ortho_unvalidated = ortho_discussion_points(detections)
    return {
        'patient': {k: (patient.get(k) or '').strip() for k in ('name', 'age', 'clinic')},
        'date': datetime.datetime.now().strftime('%d %B %Y, %H:%M'),
        'conf_threshold': conf_threshold,
        'detections': detections,
        'risk': score,
        'status': status,
        'status_text': status_text,
        'cost_rows': rows,
        'cost_min': cmin,
        'cost_max': cmax,
        'ortho_points': points,
        'ortho_unvalidated': ortho_unvalidated,
        'cam_note': cam_note,
        'tooth_estimated': any(d.get('tooth_source') == 'estimated' for d in detections),
    }


def _tooth(d):
    if d['tooth'] is None:
        return '—'
    return f"{d['tooth']}{'~' if d.get('tooth_source') == 'estimated' else ''}"


def _sorted_findings(detections):
    """One entry per (class, tooth), keeping the most confident detection and
    a count of boxes, most severe first."""
    groups = {}
    for d in detections:
        key = (d['class'], d['tooth'])
        g = groups.get(key)
        if g is None or d['conf'] > g['conf']:
            groups[key] = dict(d, count=(g['count'] if g else 0) + 1)
        else:
            g['count'] += 1
    return sorted(groups.values(), key=lambda d: (not d['reliable'],
                                                  -SEVERITY_ORDER[d['severity']], -d['conf']))


def _name(d):
    return d['class'] + (f" (×{d['count']})" if d['count'] > 1 else '')


def _inr(n):
    return f'₹{n:,}'


# ── Plain text (UI) ───────────────────────────────────────────
def report_text(s):
    p = s['patient']
    dets = s['detections']
    reliable = [d for d in dets if d['reliable']]
    unvalidated = [d for d in dets if not d['reliable']]
    L = []
    L.append('DENTAL AI ANALYSIS REPORT')
    L.append('=' * 60)
    if any(p.values()):
        L.append(f"Patient : {p['name'] or 'N/A'}    Age: {p['age'] or 'N/A'}    Clinic: {p['clinic'] or 'N/A'}")
    L.append(f"Date    : {s['date']}")
    L.append(f"Findings: {len(dets)} at confidence ≥ {s['conf_threshold']:.2f} "
             f"({len(reliable)} validated, {len(unvalidated)} unvalidated)")
    L.append(f"Risk    : {s['risk']:.0f}/100 — {s['status']}: {s['status_text']}")
    L.append('')

    L.append('FINDINGS (validated classes)')
    L.append('-' * 60)
    if reliable:
        for d in _sorted_findings(reliable):
            L.append(f"  Tooth {_tooth(d):<4} {_name(d):<26} {CATEGORY_LABELS.get(d['category'], d['category']):<15}"
                     f" severity: {d['severity']:<8} confidence: {d['conf']*100:.0f}% ({d['confidence']})")
    else:
        L.append('  None')
    L.append('')

    if unvalidated:
        L.append(f'UNVALIDATED FINDINGS (classes with {gating_rule()})')
        L.append('-' * 60)
        L.append('  The model is not reliable for these classes. They are listed for')
        L.append('  completeness and are excluded from risk, cost and recommendations.')
        for d in _sorted_findings(unvalidated):
            L.append(f"  Tooth {_tooth(d):<4} {_name(d):<26} confidence: {d['conf']*100:.0f}%  "
                     f"[{reliability_note(d['class'])}]")
        L.append('')

    L.append('ORTHODONTIC DISCUSSION POINTS (for your dentist / orthodontist)')
    L.append('-' * 60)
    if s['ortho_points']:
        for pt in s['ortho_points']:
            teeth = ', '.join(map(str, pt['teeth'])) or '—'
            L.append(f"  {pt['title']} — teeth {teeth} (max confidence {pt['max_conf']*100:.0f}%)")
            L.append(f"    {pt['note']}")
            for name, why in pt['options']:
                L.append(f"    • {name}: {why}")
    else:
        L.append('  No validated orthodontic findings.')
    if s['ortho_unvalidated']:
        L.append(f"  Not assessed (model not validated): {', '.join(s['ortho_unvalidated'])}")
    L.append('  A panoramic X-ray alone cannot diagnose malocclusion; a clinical exam is required.')
    L.append('')

    L.append(cost_text(s))
    L.append('')
    if s['tooth_estimated']:
        L.append('~ Tooth number estimated from position in the image; verify clinically.')
    if s['cam_note']:
        L.append(f"Explanation map: {s['cam_note']}")
    L.append('')
    L.append(DISCLAIMER)
    return '\n'.join(L)


def cost_text(s):
    L = ['INDICATIVE TREATMENT COSTS (INR, validated findings only)', '-' * 60]
    if not s['cost_rows']:
        L.append('  No validated findings that need treatment.')
        return '\n'.join(L)
    for r in s['cost_rows']:
        L.append(f"  {r['class']:<18} ×{r['teeth']:<2} {r['treatment']:<28} "
                 f"{_inr(r['min'])} – {_inr(r['max'])}   {r['urgency']}")
    L.append(f"  {'TOTAL':<50} {_inr(s['cost_min'])} – {_inr(s['cost_max'])}")
    L.append(f'  {COST_REGION_NOTE}')
    return '\n'.join(L)


# ── PDF ───────────────────────────────────────────────────────
def find_unicode_font():
    """Path to DejaVuSans.ttf (bundled with matplotlib) or None."""
    candidates = []
    try:
        import matplotlib
        candidates.append(os.path.join(os.path.dirname(matplotlib.__file__),
                                       'mpl-data', 'fonts', 'ttf', 'DejaVuSans.ttf'))
    except ImportError:
        pass
    candidates += ['/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf']
    candidates += glob.glob('/usr/share/fonts/**/DejaVuSans.ttf', recursive=True)
    for c in candidates:
        if os.path.exists(c):
            return c
    return None


class ReportPDF(FPDF):
    def __init__(self, clinic, font_path):
        super().__init__()
        self.clinic = clinic
        self.unicode = font_path is not None
        if self.unicode:
            self.add_font('Body', '', font_path)
            bold = font_path.replace('DejaVuSans.ttf', 'DejaVuSans-Bold.ttf')
            self.add_font('Body', 'B', bold if os.path.exists(bold) else font_path)
            self.add_font('Body', 'I', font_path)
            self.family = 'Body'
        else:
            self.family = 'Helvetica'
        self.set_auto_page_break(auto=True, margin=18)

    def t(self, text):
        if self.unicode:
            return text
        return (text.replace('₹', 'Rs ').replace('—', '-').replace('–', '-').replace('≥', '>=')
                .replace('•', '-').replace('×', 'x').encode('latin-1', 'replace').decode('latin-1'))

    def header(self):
        self.set_fill_color(20, 60, 120)
        self.rect(0, 0, 210, 22, 'F')
        self.set_text_color(255, 255, 255)
        self.set_font(self.family, 'B', 15)
        self.set_xy(0, 4)
        self.cell(210, 8, self.t(self.clinic or 'Dental AI Analyzer'), align='C')
        self.set_font(self.family, '', 9)
        self.set_xy(0, 13)
        self.cell(210, 6, 'AI-assisted panoramic X-ray analysis (research tool)', align='C')
        self.set_text_color(0, 0, 0)
        self.set_y(28)

    def footer(self):
        self.set_y(-12)
        self.set_font(self.family, '', 7)
        self.set_text_color(120, 120, 120)
        self.cell(0, 6, self.t(f'Dental AI Analyzer v3  |  Not a diagnosis  |  Page {self.page_no()}/{{nb}}'),
                  align='C')
        self.set_text_color(0, 0, 0)

    def section(self, title, keep=0):
        """Section bar; starts a new page unless ``keep`` mm of content fit below it."""
        if self.get_y() > 250 or self.get_y() + 12 + keep > 280:
            self.add_page()
        self.ln(3)
        self.set_font(self.family, 'B', 11)
        self.set_fill_color(30, 80, 160)
        self.set_text_color(255, 255, 255)
        self.cell(0, 7, self.t('  ' + title), fill=True, new_x='LMARGIN', new_y='NEXT')
        self.set_text_color(0, 0, 0)
        self.ln(2)

    def para(self, text, size=9, style=''):
        self.set_font(self.family, style, size)
        self.multi_cell(0, 4.8, self.t(text), new_x='LMARGIN', new_y='NEXT')

    @staticmethod
    def image_size(img, max_h=110):
        """(width, height) in mm: full text width, capped at ``max_h`` tall."""
        w, h = img.size
        width = min(190, max_h * w / h)
        return width, width * h / w

    def image_block(self, img, max_h=110):
        width, height = self.image_size(img, max_h)
        if self.get_y() + height > 280:
            self.add_page()
        self.image(img, x=(210 - width) / 2, w=width)
        self.ln(2)

    def table_block(self, header, rows, widths):
        self.set_font(self.family, '', 8)
        self.set_fill_color(255, 255, 255)        # section bars leave a blue fill behind
        heading = FontFace(emphasis='BOLD', fill_color=(222, 230, 246))
        with self.table(col_widths=widths, width=sum(widths), align='LEFT', text_align='LEFT',
                        line_height=5, cell_fill_mode='ROWS', cell_fill_color=(244, 247, 252),
                        headings_style=heading) as table:
            r = table.row()
            for h in header:
                r.cell(self.t(h))
            for row in rows:
                r = table.row()
                for c in row:
                    r.cell(self.t(str(c)))
        self.ln(2)


def export_pdf(summary, annotated_img=None, cam_img=None, fdi_img=None, out_dir=None):
    """Writes the report to a unique temporary file and returns its path.
    Images are PIL images (or None)."""
    s = summary
    p = s['patient']
    pdf = ReportPDF(p['clinic'], find_unicode_font())
    pdf.alias_nb_pages()
    pdf.add_page()

    pdf.set_font(pdf.family, 'B', 10)
    pdf.cell(95, 6, pdf.t(f"Patient: {p['name'] or 'N/A'}"))
    pdf.set_font(pdf.family, '', 9)
    pdf.cell(95, 6, pdf.t(f"Date: {s['date']}"), new_x='LMARGIN', new_y='NEXT')
    pdf.set_font(pdf.family, 'B', 10)
    pdf.cell(95, 6, pdf.t(f"Age: {p['age'] or 'N/A'}"))
    pdf.set_font(pdf.family, '', 9)
    pdf.cell(95, 6, pdf.t(f"Confidence threshold: {s['conf_threshold']:.2f}"), new_x='LMARGIN', new_y='NEXT')
    pdf.ln(2)

    pdf.set_fill_color(255, 243, 205)
    pdf.set_draw_color(220, 180, 0)
    pdf.set_font(pdf.family, '', 8)
    pdf.multi_cell(0, 4.5, pdf.t(DISCLAIMER), border=1, fill=True, new_x='LMARGIN', new_y='NEXT')
    pdf.set_draw_color(0, 0, 0)

    pdf.section('SUMMARY')
    reliable = [d for d in s['detections'] if d['reliable']]
    unvalidated = [d for d in s['detections'] if not d['reliable']]
    pdf.para(f"Risk score: {s['risk']:.0f}/100 — {s['status']}: {s['status_text']}", 10, 'B')
    pdf.para(f"{len(reliable)} validated findings, {len(unvalidated)} findings from classes the model "
             f"is not validated on ({gating_rule()}).")

    if annotated_img is not None:
        pdf.section('ANNOTATED X-RAY', keep=pdf.image_size(annotated_img)[1])
        pdf.image_block(annotated_img)
    if fdi_img is not None:
        pdf.section('TOOTH CHART (FDI)', keep=pdf.image_size(fdi_img, 70)[1])
        pdf.image_block(fdi_img, max_h=70)

    pdf.section('FINDINGS')
    if reliable:
        rows = [(_tooth(d), _name(d), CATEGORY_LABELS.get(d['category'], d['category']),
                 d['severity'], f"{d['conf']*100:.0f}%") for d in _sorted_findings(reliable)]
        pdf.table_block(['Tooth', 'Finding', 'Category', 'Severity', 'Confidence'], rows,
                        (14, 50, 34, 22, 22))
    else:
        pdf.para('No validated findings.')
    if unvalidated:
        pdf.para('Unvalidated (shown for completeness, excluded from risk and costs):', 9, 'B')
        rows = [(_tooth(d), _name(d), f"{d['conf']*100:.0f}%",
                 reliability_note(d['class']))
                for d in _sorted_findings(unvalidated)]
        pdf.table_block(['Tooth', 'Finding', 'Confidence', 'Why unvalidated'], rows, (14, 56, 24, 46))
    if s['tooth_estimated']:
        pdf.para('~ tooth number estimated from position in the image.', 8)

    pdf.section('ORTHODONTIC DISCUSSION POINTS')
    if s['ortho_points']:
        for pt in s['ortho_points']:
            teeth = ', '.join(map(str, pt['teeth'])) or '—'
            pdf.para(f"{pt['title']} (teeth {teeth})", 9, 'B')
            pdf.para(pt['note'], 8)
            for name, why in pt['options']:
                pdf.para(f"• {name}: {why}", 8)
            pdf.ln(1)
    else:
        pdf.para('No validated orthodontic findings.')
    if s['ortho_unvalidated']:
        pdf.para(f"Not assessed (model not validated): {', '.join(s['ortho_unvalidated'])}", 8)
    pdf.para('A panoramic X-ray alone cannot diagnose malocclusion; a clinical exam is required.', 8, 'I')

    pdf.section('INDICATIVE TREATMENT COSTS (INR)')
    if s['cost_rows']:
        rows = [(r['class'], r['teeth'], r['treatment'], f"{_inr(r['min'])} – {_inr(r['max'])}", r['urgency'])
                for r in s['cost_rows']]
        rows.append(('Total', '', '', f"{_inr(s['cost_min'])} – {_inr(s['cost_max'])}", ''))
        pdf.table_block(['Finding', 'Teeth', 'Typical treatment', 'Range', 'Urgency'], rows,
                        (34, 12, 50, 50, 30))
        pdf.para(COST_REGION_NOTE, 8)
    else:
        pdf.para('No validated findings that need treatment.')

    if cam_img is not None:
        pdf.section('EXPLANATION MAP', keep=pdf.image_size(cam_img)[1] + 10)
        if s['cam_note']:
            pdf.para(s['cam_note'], 8)
        pdf.image_block(cam_img)

    fd, path = tempfile.mkstemp(prefix='dental_report_', suffix='.pdf', dir=out_dir)
    os.close(fd)
    pdf.output(path)
    return path
